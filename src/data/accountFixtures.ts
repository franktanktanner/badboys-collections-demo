const officeByName = new Map(agencyConfig.offices.map((office) => [office.name, office]));

function officeIdFor(office: Office): string {
  return officeByName.get(office)?.id ?? `office-${office.toLowerCase().replaceAll(' ', '-')}`;
}

function buildAccount(input: FixtureInput): Account {
  const defendantId = `${input.id}-defendant`;
  const indemnitorId = `${input.id}-indemnitor`;
  const bond = {
    id: `${input.id}-bond`,
    accountId: input.id,
    bondId: input.bondId,
    bondAmount: input.bondAmount,
    premiumRate: 0.08,
    bondDate: input.bondDate,
    courtCaseNumber: `CA-${input.bondId.replace('BB-', '')}`,
  };
  const balance = {
    accountId: input.id,
    originalAmount: input.bondAmount,
    amountOwed: input.amountOwed,
    recoveredAmount: input.recoveredAmount,
    lastPaymentAt: input.payments.find((payment) => payment.status === 'Cleared')?.date,
    daysPastDue: input.daysPastDue,
  };

  return {
    id: input.id,
    agencyId,
    officeId: officeIdFor(input.office),
    bondId: input.bondId,
    defendant: {
      name: input.defendantName,
      dob: input.defendantDob,
      charges: input.charges,
      bondDate: input.bondDate,
      courtDate: input.courtDate,
    },
    indemnitor: {
      name: input.indemnitorName,
      phone: input.phone,
      email: input.email,
      address: input.address,
      employer: input.employer,
    },
    contacts: [
      {
        id: defendantId,
        accountId: input.id,
        agencyId,
        kind: 'defendant',
        name: input.defendantName,
        relationship: 'Defendant',
        preferredContactMethod: 'letter',
      },
      {
        id: indemnitorId,
        accountId: input.id,
        agencyId,
        kind: 'indemnitor',
        name: input.indemnitorName,
        phone: input.phone,
        email: input.email,
        address: input.address,
        employer: input.employer,
        relationship: 'Primary indemnitor',
        preferredContactMethod: input.compliance?.preferredContactMethod ?? 'sms',
        contactWindowStart: input.compliance?.contactWindowStart,
        contactWindowEnd: input.compliance?.contactWindowEnd,
      },
    ],
    bondAmount: input.bondAmount,
    amountOwed: input.amountOwed,
    daysPastDue: input.daysPastDue,
    riskScore: input.riskScore,
    status: input.status,
    recoveryStatus: input.recoveryStatus,
    priority: input.priority,
    office: input.office,
    lastContact: input.lastContact,
    nextAction: input.nextAction,
    payments: input.payments,
    communications: input.communications,
    bond,
    balance,
    compliance: input.compliance,
    outreachEvents: input.communications.map((communication, index) => ({
      id: `${input.id}-outreach-${index + 1}`,
      agencyId,
      accountId: input.id,
      contactId: indemnitorId,
      channel: communication.channel === 'AI Call'
        ? 'ai_call'
        : communication.channel === 'SMS'
          ? 'sms'
          : communication.channel === 'Email'
            ? 'email'
            : communication.channel === 'Skip Trace'
              ? 'skip_trace'
              : 'letter',
      outcome: communication.outcome.toLowerCase().includes('promise')
        ? 'promise_logged'
        : communication.outcome.toLowerCase().includes('payment')
          ? 'payment_collected'
          : 'completed',
      summary: communication.outcome,
      createdAt: communication.date,
      createdBy: 'fixture',
    })),
    promisesToPay: input.promisesToPay,
    paymentPlans: input.paymentPlans,
    handoffs: input.handoffs,
    recoveryActions: [],
    createdAt: input.bondDate,
    updatedAt: input.lastContact,
  };
}

